import type {
  CandidateRoute,
  MarsSite,
  MarsCoordinate,
  MapLayerConfig,
  MissionRoutePlan
} from '../types/mars';
import { formatMarsCoordinate, formatElevation } from './marsMath';

export interface ReportConfig {
  selectedSite: MarsSite | null;
  selectedCoordinate: MarsCoordinate | null;
  activeLayer: MapLayerConfig;
  missionRoute: MissionRoutePlan;
  activeRoute?: CandidateRoute;
}

/**
 * Generates a scientific Markdown mission report.
 */
export function generateMarkdownReport(config: ReportConfig): string {
  const timestamp = new Date().toUTCString();
  const site = config.selectedSite;
  const route = config.activeRoute;
  const layer = config.activeLayer;

  return `# GeoMars Mission & Planetary Terrain Report
**Generated by**: GeoMars NASA Exploration System
**Timestamp**: ${timestamp}
**Coordinate Reference System**: IAU 2000 Mars (EPSG:4326 Equirectangular)
**Planetary Datum**: 0-meter MOLA Areoid equipotential surface

---

## 1. Primary Target Region
- **Target Name**: ${site ? site.name : 'Custom Surface Geolocation'}
- **Classification**: ${site ? site.category.toUpperCase() : 'Surface Coordinate'}
- **Coordinates**: ${
    config.selectedCoordinate
      ? formatMarsCoordinate(config.selectedCoordinate.lat, config.selectedCoordinate.lng)
      : '18.38° N, 77.58° E'
  }
- **MOLA Elevation**: ${
    config.selectedCoordinate?.elevationMeters !== undefined
      ? formatElevation(config.selectedCoordinate.elevationMeters)
      : 'Uncalibrated'
  }
${
  site
    ? `- **Geological Stratigraphy**: ${site.geology}\n- **Historical Mission Context**: ${
        site.mission || 'Orbital Survey'
      } (${site.agency || 'NASA'})\n- **Scientific Highlights**: ${site.scienceHighlights.join('; ')}`
    : ''
}

---

## 2. Active Cartographic & Remote Sensing Datasets
- **Primary Raster**: ${layer.name} (${layer.subtitle || 'Standard'})
- **Provider / Instrument**: ${layer.provider}
- **Resolution**: ${layer.resolution}
- **Service Protocol**: ${layer.serviceType.toUpperCase()}
- **Dataset Description**: ${layer.description}
- **Calibration Status**: Verified operational

---

## 3. Rover Expedition Traverse Plan
${
  route
    ? `
- **Route Name**: ${route.name}
- **Waypoint Alpha (Start)**: ${config.missionRoute.startLabel}
- **Waypoint Omega (Destination)**: ${config.missionRoute.destinationLabel}
- **Plan Distance**: ${route.distanceKm.toFixed(1)} km
- **Estimated Operational Sols**: ~${route.estimatedSolDays} Sols (at 120 m/sol nominal drive rate)
- **Topographic Cost Score**: ${route.terrainCostScore}
- **Maximum Gradient Slope**: ${route.maxSlopeDeg}°
- **Mean Gradient Slope**: ${route.avgSlopeDeg}°
- **Elevation Variation Delta**: ${route.elevationDeltaMeters} meters
- **Traverse Difficulty Assessment**: ${route.difficulty}
`
    : `*No active rover expedition route plotted during this session.*`
}

---

## 4. Methodology, Assumptions & Planetary Constraints
1. **Distance Metric**: Calculated using great-circle spherical geodesy on the Mars volumetric mean radius ($R = 3,389.5\\text{ km}$).
2. **Topographic Altimetry**: Elevation metrics referenced against the Mars Global Surveyor (MGS) Mars Orbiter Laser Altimeter (MOLA) Megdr model.
3. **Slope Derivation**: Calculated at regional baseline scales ($\\Delta h / \\Delta d$). Local sub-meter obstacles (boulders, dunes) require localized HiRISE digital terrain models (DTMs) and active Terrain-Relative Navigation (TRN).
4. **Rover Mobility Model**: Assumes a multi-mission radioisotope thermoelectric generator (MMRTG) vehicle (Perseverance/Curiosity class) with a maximum safe operational incline of 30° and nominal transit speed of 0.12 km/Sol.

---

## 5. Certification & Data Provenance
- **Data Archive**: NASA Planetary Data System (PDS) Cartography and Imaging Sciences Node (IMG).
- **Cartographic Partner**: USGS Astrogeology Science Center, Flagstaff, Arizona.
- **ESA Mars Express**: High Resolution Stereo Camera (HRSC) team.
`;
}

/**
 * Downloads a string as a text file in browser.
 */
export function downloadFile(content: string, filename: string, mimeType = 'text/plain') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

